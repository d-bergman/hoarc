import { chromium } from 'playwright';
import AxeBuilder from '@axe-core/playwright';
import { createRequire } from 'node:module';
import { execFileSync } from 'node:child_process';
import { readFile, writeFile, rm } from 'node:fs/promises';
import assert from 'node:assert/strict';

if (!process.env.FIREBASE_AUTH_EMULATOR_HOST || !process.env.FIREBASE_DATABASE_EMULATOR_HOST) throw new Error('Run inside Firebase emulators with project demo-hoarc.');
const require = createRequire(new URL('../functions/package.json', import.meta.url));
const { initializeApp, deleteApp } = require('firebase-admin/app');
const { getAuth } = require('firebase-admin/auth');
const { getDatabase } = require('firebase-admin/database');
const app = initializeApp({ projectId: 'demo-hoarc', databaseURL: 'https://demo-hoarc-default-rtdb.firebaseio.com' }, 'browser-tests');
const auth = getAuth(app); const db = getDatabase(app);
const browser = await chromium.launch({ headless: true });
const report = { tests: [] };
const settingsPath = 'artifacts/emulator-settings.local.json';
try {
  const hosted = await browser.newPage();
  const cspErrors = []; hosted.on('pageerror', error => cspErrors.push(error.message));
  hosted.on('console', msg => { if (msg.type() === 'error' && /Content Security Policy/.test(msg.text())) cspErrors.push(msg.text()); });
  const hostedResponse = await hosted.goto('http://127.0.0.1:5000/about.html');
  report.hostingHeadersApplied = !!hostedResponse.headers()['content-security-policy'];
  await hosted.locator('[data-bio-trigger="donna"]').click();
  await hosted.locator('#bio-donna.show').waitFor();
  await hosted.keyboard.press('Escape');
  assert.deepEqual(cspErrors, []);
  await hosted.close();
  report.tests.push('Firebase Hosting emulator serves the staging page with working modal scripts. Custom-header verification remains a deployed check on Windows.');
  const settings = JSON.parse(await readFile('site.settings.json', 'utf8'));
  await writeFile(settingsPath, JSON.stringify({ ...settings, contactEnabled: true, contactEndpoint: "/api/contact/", announcementsEnabled: true, emulators: true }));
  execFileSync(process.execPath, ['scripts/build.mjs'], { env: { ...process.env, HOARC_SETTINGS: settingsPath }, stdio: 'inherit' });
  const email = `browser-admin-${Date.now()}@example.com`; const password = 'Emulator-Only-Password!';
  const user = await auth.createUser({ email, password }); await auth.setCustomUserClaims(user.uid, { admin: true });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
  const page = await context.newPage();
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto('http://127.0.0.1:4174/admin.html');
  await page.locator('#admin-email').fill(email); await page.locator('#admin-password').fill(password);
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await page.locator('#admin-workspace').waitFor({ state: 'visible' });
  await page.locator('#announcement-title').fill('Sunday entrance update');
  await page.locator('#announcement-message').fill('<script>alert("unsafe")</script> Please use the first-floor entrance.');
  await page.locator('#announcement-enabled').check();
  await page.locator('#announcement-priority').selectOption('urgent');
  assert.equal(await page.locator('#announcement-save').isDisabled(), true);
  await page.getByRole('button', { name: 'Preview', exact: true }).click();
  assert.equal(await page.locator('#announcement-preview script').count(), 0);
  assert.ok((await page.locator('#announcement-preview').textContent()).includes('<script>'));
  await page.locator('#announcement-save').click();
  await page.waitForFunction(() => document.querySelector('#admin-status').textContent.startsWith('Saved.'));
  await page.getByRole('button', { name: 'Preview', exact: true }).click();
  await page.locator('#announcement-title').fill('Changed after preview');
  assert.equal(await page.locator('#announcement-save').isDisabled(), true);
  report.tests.push('Admin sign-in, preview requirement, safe plain-text rendering, publication, and preview invalidation.');
  const audit = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag22aa']).analyze();
  assert.deepEqual(audit.violations.map(v => v.id), []);
  await page.screenshot({ path: 'artifacts/screenshots/admin-signed-in.png', fullPage: true });
  const visitor = await browser.newContext(); const home = await visitor.newPage();
  await home.goto('http://127.0.0.1:4174/');
  await home.locator('#announcements').waitFor({ state: 'visible' });
  assert.ok((await home.locator('[data-announcements]').textContent()).includes('Sunday entrance update'));
  assert.equal(await home.locator('[data-announcements] script').count(), 0);
  const records = (await db.ref('announcementState/records').get()).val();
  const key = Object.entries(records).find(([, record]) => record.title === 'Sunday entrance update')[0];
  const projected = (await db.ref(`announcementState/published/${key}`).get()).val();
  await db.ref(`announcementState/published/${key}`).update({ ...projected, expiresAt: Date.now() + 2000 });
  await home.waitForFunction(() => !document.querySelector('[data-announcements]').textContent.includes('Sunday entrance update'), { timeout: 7000 });
  report.tests.push('Anonymous RTDB feed updates live, escapes HTML, and removes expired notices without rebuilding.');
  const contact = await visitor.newPage();
  await contact.goto('http://127.0.0.1:4174/contact.html');
  const formAudit = await new AxeBuilder({ page: contact }).withTags(['wcag2a', 'wcag2aa', 'wcag22aa']).analyze();
  assert.deepEqual(formAudit.violations.map(v => v.id), []);
  let submitted;
  await contact.route('**/api/contact/', route => { submitted = route.request().postDataJSON(); return route.fulfill({ status: 200, contentType: 'application/json', body: '{"ok":true}' }); });
  async function fillForm() {
    await contact.locator('#contact-first-name').fill('Test'); await contact.locator('#contact-last-name').fill('Visitor'); await contact.locator('#contact-email').fill('visitor@example.com');
    await contact.locator('#contact-subject').fill('First visit'); await contact.locator('#contact-message').fill('Which entrance should I use?');
    await contact.locator('#contact-consent').check();
  }
  await fillForm(); await contact.getByRole('button', { name: 'Send message' }).click();
  await contact.waitForFunction(() => document.querySelector('#contact-status').textContent.includes('accepted for delivery'));
  assert.equal(submitted.consent, true); assert.equal(submitted.email, 'visitor@example.com');
  await contact.unroute('**/api/contact/');
  await contact.route('**/api/contact/', route => route.fulfill({ status: 503, contentType: 'application/json', body: '{"ok":false,"message":"Please email or call us."}' }));
  await fillForm(); await contact.getByRole('button', { name: 'Send message' }).click();
  await contact.waitForFunction(() => document.querySelector('#contact-status').textContent === 'Please email or call us.');
  assert.equal(await contact.locator('#contact-message').inputValue(), 'Which entrance should I use?');
  report.tests.push('Contact form accessibility, consent, accepted response, and failure retaining the message; HTTP responses mocked, no email sent.');
  await contact.screenshot({ path: 'artifacts/screenshots/contact-form.png', fullPage: true });
  assert.deepEqual(errors, []);
  await page.locator('#admin-signout').click(); await page.locator('#admin-login').waitFor({ state: 'visible' });
  assert.equal(await page.locator('#admin-workspace').isVisible(), false);
  report.tests.push('Signing out hides private management controls.');
  console.log('Emulator browser checks passed. No live Firebase data or real email used.');
} finally {
  await writeFile('artifacts/emulator-browser-report.json', JSON.stringify(report, null, 2));
  await browser.close(); await deleteApp(app); await rm(settingsPath, { force: true });
  const env = { ...process.env }; delete env.HOARC_SETTINGS;
  execFileSync(process.execPath, ['scripts/build.mjs'], { env, stdio: 'inherit' });
}
